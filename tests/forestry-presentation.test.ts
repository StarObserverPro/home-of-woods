import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {Models} from '../src/scene/models.ts';
import {Resources} from '../src/scene/resources.ts';
import {createForestryPresentation} from '../src/scene/forestry-presentation.ts';
import {createState} from '../src/domain/state.ts';
import {startChop,advanceForestry} from '../src/domain/forestry.ts';
import {FORESTRY} from '../src/content/forestry.ts';
import {heightAt} from '../src/world/surface.ts';
import type {Tree} from '../src/world/layout.ts';

test('production GLB presentation swings an axe, tips the committed tree, preserves a pickable stump and never settles state',async()=>{
  const resources=new Resources(),models=new Models(resources),loader=new GLTFLoader();
  for(const name of ['pine','broadleaf','ranger']){
    const bytes=await readFile(new URL(`../public/assets/m0/${name}.glb`,import.meta.url));
    const gltf=await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength) as ArrayBuffer,'');
    gltf.scene.traverse(o=>{if(o instanceof THREE.Mesh){resources.own(o.geometry);for(const m of Array.isArray(o.material)?o.material:[o.material])resources.own(m);}});
    models.templates.set(name,gltf.scene);
  }
  const trees:Tree[]=[{id:'test-pine',individualId:'test-pine:g0',generation:0,x:-35,z:15,kind:'pine',scale:1.1,variant:.2,role:'managed'},
    {id:'test-leaf',individualId:'test-leaf:g0',generation:0,x:-49,z:15,kind:'broadleaf',scale:1.1,variant:.2,role:'managed'}];
  const forest=models.createForest(trees),player=models.clone('ranger');
  const limbs=['leg_L','leg_R','arm_L','arm_R'].map(name=>{let found:THREE.Object3D|undefined;player.traverse(o=>{if(o.name.startsWith(name))found=o;});return found;});
  const presenter=createForestryPresentation({resources,forestGroup:forest.group,trees,selections:forest.selections,player,limbs});
  const state=createState(trees),byId=new Map(trees.map(t=>[t.id,t])),tree=trees[0],root=forest.selections.get(tree.id)!;
  state.player.x=tree.x+1.7;state.player.z=tree.z;state.selected=tree.id;player.position.set(state.player.x,heightAt(state.player.x,state.player.z),state.player.z);
  presenter.update(state);const original=root.quaternion.clone(),allocations=resources.stats();
  assert.equal(startChop(state,tree).ok,true);state.time=1.4;advanceForestry(state,byId);
  presenter.update(state);assert.equal(player.getObjectByName('forestry-hand-axe')?.visible,true);assert.notEqual(limbs[3]?.rotation.x,0);
  const unchanged=JSON.stringify(state);
  for(let i=0;i<100;i++)presenter.update(state);
  assert.equal(JSON.stringify(state),unchanged,'animation does not mutate state or create rewards');assert.deepEqual(resources.stats(),allocations,'fixed shared allocations');
  state.time=FORESTRY.chopSeconds+.7;advanceForestry(state,byId);presenter.update(state);
  assert.ok(root.quaternion.angleTo(original)>.1,'whole production tree rotates from its base');assert.equal(root.visible,true);
  assert.equal(player.getObjectByName('forestry-hand-axe')?.visible,false);assert.ok(!presenter.getPickTargets().includes(root));
  const wood=state.forestry.wood;for(let i=0;i<50;i++)presenter.update(state);assert.equal(state.forestry.wood,wood);
  state.time=FORESTRY.chopSeconds+FORESTRY.fallSeconds;advanceForestry(state,byId);presenter.update(state);
  assert.equal(state.forestry.slots[tree.id].status,'stump');assert.equal(state.forestry.active,null);
  assert.equal(root.visible,true,'committed stump retains the landed source tree briefly');
  assert.ok(root.quaternion.angleTo(original)>1,'resting source keeps its final fallen pose');
  assert.ok(!presenter.getPickTargets().includes(root),'visible fallen tree is never pickable');
  assert.ok(presenter.getPickTargets().some(o=>o.name===tree.id&&o.userData.forestryRole==='stump'));
  const chips=forest.group.getObjectByName('forestry-hit-chips') as THREE.InstancedMesh;
  assert.equal(chips.visible,true,'landing reuses the existing chip pool after the action ends');
  const landedState=JSON.stringify(state),landedPose=root.quaternion.clone();
  for(let i=0;i<100;i++)presenter.update(state);
  assert.equal(JSON.stringify(state),landedState,'landing rest and scatter never mutate gameplay state');
  assert.deepEqual(resources.stats(),allocations,'landing allocates no shared GPU resources');
  presenter.update(state,true);assert.equal(chips.visible,false,'reduced motion omits landing scatter');assert.equal(root.visible,true);
  state.time=state.forestry.slots[tree.id].felledAt!+FORESTRY.fallSeconds+1.79;presenter.update(state);
  assert.equal(root.visible,true);assert.ok(root.quaternion.angleTo(landedPose)<1e-7,'landed tree holds a stable pose');assert.equal(chips.visible,false);
  state.time+=.02;const hiddenState=JSON.stringify(state);presenter.update(state);
  assert.equal(root.visible,false,'landed source hides after 1.8 simulation seconds');
  assert.equal(JSON.stringify(state),hiddenState);assert.equal(state.forestry.wood,wood);
  assert.ok(!presenter.getPickTargets().includes(root));
  assert.ok(presenter.getPickTargets().some(o=>o.name===tree.id&&o.userData.forestryRole==='stump'));
  state.time=state.forestry.slots[tree.id].regrowAt!+.01;advanceForestry(state,byId);presenter.update(state);
  assert.equal(root.visible,true);assert.ok(root.scale.x<tree.scale*.3);assert.ok(presenter.getPickTargets().includes(root));
  const shared=new Set<THREE.BufferGeometry|THREE.Material>();
  for(const group of [forest.group,player])group.traverse(o=>{if(o instanceof THREE.Mesh){shared.add(o.geometry);for(const material of Array.isArray(o.material)?o.material:[o.material])shared.add(material);}});
  const releases=new Map([...shared].map(resource=>[resource,0]));
  for(const resource of shared)resource.addEventListener('dispose',()=>releases.set(resource,releases.get(resource)!+1));
  let poolReleases=0;chips.addEventListener('dispose',()=>poolReleases++);
  presenter.dispose();presenter.dispose();assert.equal(player.getObjectByName('forestry-hand-axe'),undefined);assert.equal(forest.group.getObjectByName('forestry-hit-chips'),undefined);
  assert.equal(poolReleases,1);assert.ok([...releases.values()].every(count=>count===0),'adapter does not release shared geometry or materials');
  resources.dispose();resources.dispose();assert.ok([...releases.values()].every(count=>count===1),'shared owner releases each observed resource exactly once');
  assert.deepEqual(resources.stats(),{geometries:0,materials:0,extras:0,disposed:true});
});
