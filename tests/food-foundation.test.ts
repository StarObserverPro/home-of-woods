const grant=(state:ReturnType<typeof createState>,itemId:string,quantity:number)=>{
  state.inventory=inventoryTransaction(state.inventory,[{itemId,qualityId:'ordinary',delta:quantity}]);
};
const at=(state:ReturnType<typeof createState>,id:string,point:{x:number;z:number})=>{
  state.selected=id;state.player.x=point.x;state.player.z=point.z;
};
test('merchant bundle is one atomic exchange, varied and stable across saves',()=>{
  assert.deepEqual(foodSackContents(104729,1),foodSackContents(104729,1));
  assert.notDeepEqual(foodSackContents(104729,1),foodSackContents(104729,2));
  const state=createState();at(state,CAMP_VISITOR.id,CAMP_VISITOR);
  const before=JSON.stringify(state.inventory);
  assert.match(tradeFoodSack(state),/需要 2 份/);
  assert.equal(JSON.stringify(state.inventory),before);
  grant(state,'mushroom',2);
  const previous=state.inventory.stacks.reduce((n,s)=>n+s.quantity,0);
  assert.match(tradeFoodSack(state),/一麻袋/);
  const bag=foodSackContents(state.seed,1);
  assert.equal(inventoryCount(state.inventory,'mushroom'),0);
  for(const item of bag)assert.equal(inventoryCount(state.inventory,item.itemId),item.quantity);
  assert.equal(state.inventory.stacks.reduce((n,s)=>n+s.quantity,0),previous-2+bag.reduce((n,i)=>n+i.quantity,0));
  assert.equal(state.food.sacksBought,1);
});
test('drying consumes only real input and completes once on the local clock',()=>{
  const state=createState();at(state,CAMP_PROPS.dryer.id,CAMP_PROPS.dryer);
  grant(state,'mushroom',2);
  assert.match(startDryMushrooms(state),/挂上/);
  assert.equal(inventoryCount(state.inventory,'mushroom'),0);
  assert.match(startDryMushrooms(state),/已有/);
  state.time=99;
  assert.equal(advanceFood(state),null);
  state.time=100;
  assert.match(advanceFood(state),/干货/);
  assert.equal(inventoryCount(state.inventory,'dried-mushroom'),1);
  assert.equal(advanceFood(state),null);
  assert.equal(inventoryCount(state.inventory,'dried-mushroom'),1);
  const service=createProcessingService(ITEM_CATALOG.items);
  assert.equal(service.definitions.get('dry-mushrooms')?.status,'configured');
});
test('dried or fresh mushrooms with any listed grain yield a traceable consumed meal',()=>{
  const state=createState();at(state,CAMP_PROPS.fire.id,CAMP_PROPS.fire);
  grant(state,'dried-mushroom',1);
  grant(state,'food-oats',1);
  state.workshop.upgrades['camp-fire:pot']={level:1,completedPaths:[],investments:[],updatedAt:0};
  state.workshop.mounted['camp-fire:top']='camp-fire:hook';
  assert.match(startMushroomSoup(state,'food-oats'),/下锅/);
  assert.equal(inventoryCount(state.inventory,'dried-mushroom'),0);
  assert.equal(inventoryCount(state.inventory,'food-oats'),0);
  assert.match(startMushroomSoup(state,'food-oats'),/正在煮/);
  state.time=8;advanceFood(state);
  assert.equal(inventoryCount(state.inventory,'forest-soup'),1);
  const soup=state.inventory.stacks.find(s=>s.itemId==='forest-soup');
  assert.deepEqual(soup?.food,{series:'mushroom-grain-soup',grain:'food-oats',fungus:'dried-mushroom'});
  assert.match(eatMushroomSoup(state),/明天/);
  assert.equal(inventoryCount(state.inventory,'forest-soup'),0);
  assert.equal(state.food.lastMealDay,1);
  assert.equal(foodSnapshot(state).nextDayReady,true);
  state.time=600;
  assert.equal(heavyLaborAllowed(state.food,state.time),true);
  state.time=1800;
  assert.equal(heavyLaborAllowed(state.food,state.time),false);
});
test('uncooked black bread breaks the no-pot/no-logging dependency after the first day',()=>{
  const state=createState();
  state.time=600;
  assert.equal(heavyLaborAllowed(state.food,state.time),false);
  at(state,CAMP_PROPS.fire.id,CAMP_PROPS.fire);
  grant(state,'food-black-bread',1);
  assert.match(eatBlackBread(state),/明天/);
  assert.equal(inventoryCount(state.inventory,'food-black-bread'),0);
  assert.equal(heavyLaborAllowed(state.food,state.time),false);
  state.time=1800;
  assert.equal(heavyLaborAllowed(state.food,state.time),true);
});
test('world save accepts optional legacy food and rejects malformed added state',()=>{
  const state=createState(),context=createSaveContext();
  const validated=validateWorldState(state,context,'runtime').state;
  assert.deepEqual(validated.food,state.food);
  const {food,...oldWorld}=state;
  const restored=validateWorldState(oldWorld,context,'persisted').state;
  assert.equal(restored.food.lastMealDay,null);
  assert.throws(()=>validateWorldState({...oldWorld,food:{lastMealDay:999}},context,'persisted'),/food/i);
});
