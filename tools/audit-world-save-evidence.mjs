import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { verifiedSourceReader } from './read-verified-source.mjs';
const root='evidence/world-save/', read=file=>JSON.parse(fs.readFileSync(root+file,'utf8'));
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const freeze=read('source-freeze.json');assert.equal(sha(JSON.stringify(freeze.files)),freeze.runtimeFingerprint);
const source=verifiedSourceReader(root+'verified-source.zip',false);
for(const file of [...freeze.files,...freeze.supportFiles])assert.equal(sha(source(file.file)),file.sha256,`Frozen world source mismatch: ${file.file}`);
const build=read('verified-build.json');assert.equal(build.runtimeFingerprint,freeze.runtimeFingerprint);
assert.equal(sha(fs.readFileSync(root+'verified-source.zip')),build.sourceArchiveSha256);
assert.equal(sha(fs.readFileSync(root+'verified-build.zip')),build.buildArchiveSha256);
const bundle=verifiedSourceReader(root+'verified-build.zip',false);
for(const file of build.files)assert.equal(sha(bundle(file.file)),file.sha256);
for(const file of build.evidenceFiles)assert.equal(sha(fs.readFileSync(root+file.file)),file.sha256,`World evidence changed: ${file.file}`);
assert.match(fs.readFileSync(root+'check.log','utf8'),new RegExp(`# pass ${build.checks.tests}\\s+# fail 0`));
const normalized=world=>{const copy=structuredClone(world);delete copy.inventory.revision;return copy;};
const before=read('chop-before-reload.json').worldState, after=read('chop-after-reload.json').worldState;
assert.deepEqual(normalized(before),normalized(after));assert.equal(after.forestry.active.phase,'chopping');
assert.equal(after.forestry.ledger.reserved,5);assert.equal(after.forestry.ledger.used,0);
const felled=read('felled-before-reload.json').worldState;
for(const name of ['felled-reload-1.json','felled-reload-2.json'])assert.deepEqual(normalized(read(name).worldState),normalized(felled));
assert.equal(felled.inventory.stacks.find(stack=>stack.itemId==='wood').quantity,5);
assert.equal(felled.inventory.stacks.find(stack=>stack.itemId==='branch').quantity,3);
assert.equal(felled.forestry.ledger.used,5);assert.equal(felled.forestry.ledger.reserved,0);assert.equal(felled.forestry.completedActions.length,1);
assert.equal(felled.forestry.slots['tree-slot-r3-hero-0'].status,'stump');
assert.equal(felled.gathering.sources['gather.tree-slot-r3-hero-0.mushrooms'].remaining,0);
const protection=read('database-protection.json'),recovery=read('database-recovery.json');
assert.equal(protection.databaseBackend,'IndexedDB');assert.equal(protection.abortedTransactionPreserved,true);
assert.equal(protection.concurrentWinners,1);assert.equal(protection.loserStatus,'conflict');
assert.equal(protection.corruptRawPreserved,true);assert.equal(protection.rawExportExact,true);assert.equal(protection.protectedStatus,'protected');
assert.deepEqual(recovery.recovery,{status:'saved',branchQuantity:0,time:0});
assert.equal(fs.readFileSync(root+'exported-corrupt.json','utf8'),'{broken-world-save');
assert.equal(read('real-page-conflict.json').save.state,'conflict');
const layout=read('layout-checks.json');
for(const view of [layout.gameMenu,layout.protectionControls]){
  assert.equal(view.scrollWidth,view.width);
  for(const button of view.buttons??view.controls)assert.ok(button.width>=43.99&&button.height>=43.99);
}
const production=read('production-smoke.json');assert.deepEqual(production.consoleErrors,[]);
assert.ok(production.scripts.length&&production.scripts.every(script=>script.includes('/assets/')&&!script.includes('@vite')));
assert.equal(production.save.canSave,true);
console.log(JSON.stringify({version:freeze.version,runtimeFingerprint:freeze.runtimeFingerprint,tests:build.checks.tests,worldReloads:3,realIndexedDB:true,result:'passed',mode:'frozen whole-world, transaction and UI evidence; live behavior checked by npm test'}));
